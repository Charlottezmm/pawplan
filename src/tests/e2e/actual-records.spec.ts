 await dialog.getByLabel('结束时间',{exact:true}).fill(`${day()}T00:15`);
 let failed=false;
 await page.route('**/api/actual-records',async(route)=>{
  if(route.request().method()==='POST'&&!failed){failed=true;const response=await route.fetch();const data=await response.json();await route.fulfill({json:{...data,status:'applied_with_readback_error',readback:{verification:'failed'}}});}else await route.continue();
 });
 await dialog.getByRole('button',{name:'保存记录',exact:true}).click();
 await expect(dialog.getByText('结果尚未核对，暂时锁定输入。重试会核对同一条记录；也可关闭后重新读取。')).toBeVisible();
