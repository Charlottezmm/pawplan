 await dialog.getByRole('button',{name:'保存记录',exact:true}).click();
 await expect(dialog).toHaveCount(0);
 expect((await pool.query('select count(*) from actual_records where workspace_id=$1',[workspaceId])).rows[0].count).toBe('1');
 // Closing an uncertain second save must also refresh from persistence, without a manual reload.
 failed=false;
 await page.getByRole('button',{name:'记一段',exact:true}).click();
 await dialog.getByLabel('做了什么').fill('喝水休息');
 await dialog.getByLabel('开始时间',{exact:true}).fill(`${day()}T00:15`);
 await dialog.getByLabel('结束时间',{exact:true}).fill(`${day()}T00:20`);
